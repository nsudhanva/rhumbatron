/**
 * Embeds demo fixture repositories into the integration Worker, which seeds them into Artifacts
 * (AGENTS.md section 54). Output: workers/integration/src/fixtures/<name>.fixture.gen.ts.
 * Usage: bun scripts/build-fixtures.ts [--check]   (--check fails when an output is stale)
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";

const root = join(import.meta.dirname, "..");
const SKIP = new Set(["node_modules", ".DS_Store"]);
const fixtures = ["acme-shop"];
const check = process.argv.includes("--check");

async function walk(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (SKIP.has(entry.name)) continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(path)));
    else out.push(path);
  }
  return out.sort();
}

let stale = 0;
for (const name of fixtures) {
  const dir = join(root, "fixtures", name);
  const files: Record<string, string> = {};
  for (const path of await walk(dir)) files[relative(dir, path)] = await readFile(path, "utf8");
  const target = join(root, "workers/integration/src/fixtures", `${name}.fixture.gen.ts`);
  const body = `// Generated by scripts/build-fixtures.ts from fixtures/${name}. Do not edit.\nexport default ${JSON.stringify(files, null, 2)} as Record<string, string>;\n`;
  const current = await readFile(target, "utf8").catch(() => "");
  if (current === body) continue;
  if (check) {
    console.error(`stale: ${relative(root, target)} (run bun scripts/build-fixtures.ts)`);
    stale += 1;
  } else {
    await writeFile(target, body);
    console.log(`wrote ${relative(root, target)} (${Object.keys(files).length} files)`);
  }
}
process.exit(stale === 0 ? 0 : 1);
